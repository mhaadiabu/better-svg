import { existsSync } from "node:fs";
import { mkdtemp, readFile, writeFile, mkdir, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { EventEmitter } from "node:events";
import { describe, it, expect, beforeEach, afterEach, vi } from "vitest";
import svgPlugin, { localSvgs, type LocalSvgOptions } from "./plugin";

const naiveSvg = `<!-- generated by icon-designer -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24"><title>Naive</title><path id="keep-me" d="M 1.000 20.000 L 23.000 4.000 Z" /></svg>
`;

let root: string;
const localModuleId = resolve(__dirname, "../core/local.ts");
const baseModuleCode = `import { registerLocalSvgs } from "@mhaadi/svg/local";\n`;

beforeEach(async () => {
  root = await mkdtemp(join(tmpdir(), "svg-pass-"));
  await mkdir(join(root, "icons"), { recursive: true });
  await writeFile(join(root, "icons", "naive.svg"), naiveSvg);
});

afterEach(() => {
  vi.restoreAllMocks();
});

const writeFixture = async (file: string, content: string) => {
  await mkdir(join(root, file, ".."), { recursive: true });
  await writeFile(join(root, file), content, "utf8");
};

const setupCatalog = async (extras: string[] = []) => {
  await mkdir(join(root, "node_modules", "@iconify-json", "testy"), { recursive: true });
  await writeFile(
    join(root, "node_modules", "@iconify-json", "testy", "icons.json"),
    JSON.stringify({
      prefix: "testy",
      width: 24,
      height: 24,
      icons: {
        house: {
          body: '<!-- catalog register preview --><path d="M 2.000 20.000"/>',
        },
      },
    }),
  );
  await writeFixture(
    "src/ui/nav.tsx",
    extras.map((line) => `${line}\n`).join("") + '<SVG name="testy:house" />\n',
  );
};

const runTransformWith = (options: LocalSvgOptions = {}) => {
  const plugin = localSvgs({ dirs: ["icons"], ...options });
  const warnings: string[] = [];
  const info: string[] = [];
  vi.spyOn(console, "log").mockImplementation((message) => {
    info.push(String(message));
  });
  plugin.configResolved?.({ root } as never);
  const context = {
    addWatchFile() {},
    warn(message: string) {
      warnings.push(message);
    },
  };
  return plugin.transform
    ?.call(context as never, baseModuleCode, localModuleId)
    .then((result) => ({ result, warnings, info }));
};

const runTransform = (svgo: unknown) =>
  runTransformWith(svgo === undefined ? {} : { svgo: svgo as never });

describe("local discovery svgo option", () => {
  it("registers raw markup when the svgo option is off", async () => {
    const run = await runTransform(undefined);
    expect(run.result?.code).toContain("<!-- generated by icon-designer -->");
  });

  it("registers markup optimized by the safe preset when the svgo option is true", async () => {
    const run = await runTransform(true);
    expect(run.result?.code).not.toContain("<!-- generated by icon-designer -->");
    expect(run.result?.code).not.toContain("1.000");
    expect(run.result?.code).toContain(String.raw`id=\"keep-me\"`);
  });

  it("passes the discovered name to function-form svgo options", async () => {
    const names: string[] = [];
    const svgo = (name: string) => {
      names.push(name);
      return name === "naive" ? { plugins: ["cleanupIds"] } : false;
    };
    const run = await runTransform(svgo as never);
    expect(names).toEqual(["naive"]);
    expect(run.result?.code).toContain("generated by icon-designer");
    expect(run.result?.code).not.toContain(String.raw`id=\"keep-me\"`);
  });
});

describe("local discovery precompiled option", () => {
  it("emits a precompiled register call when the option is on", async () => {
    const run = await runTransformWith({ precompiled: true });
    expect(run.result?.code).toContain('"precompiled":{"naive"');
    expect(run.result?.code).toContain('"tag":"svg"');
    expect(run.result?.code).toContain('"value":"M 1.000 20.000 L 23.000 4.000 Z"');
    expect(run.result?.code).toContain(String.raw`id=\"keep-me\"`);
  });

  it("emits plain markup registration when the option is off", async () => {
    const run = await runTransformWith({});
    expect(run.result?.code).not.toContain("precompiled");
  });

  it("precompiles markup already optimized by the svgo pass", async () => {
    const run = await runTransformWith({ svgo: true, precompiled: true });
    expect(run.result?.code).not.toContain("1.000");
    expect(run.result?.code).toContain('"tag":"svg"');
    expect(run.result?.code).toContain('"value":"keep-me"');
  });

  it("fails the build when a discovered file is not a valid svg", async () => {
    await writeFile(join(root, "icons", "broken.svg"), "definitely not svg", "utf8");
    const run = () => runTransformWith({ precompiled: true });
    await expect(run()).rejects.toThrow(/Precompile pass failed for "broken"/);
  });
});

describe("catalog usage scan", () => {
  it("keeps the localSvgs alias compatible with the renamed plugin", () => {
    expect(localSvgs).toBe(svgPlugin);
    expect(svgPlugin().name).toBe("@mhaadi/svg");
  });

  it("appends a scanned catalog registration after the dirs registration", async () => {
    await setupCatalog();
    const run = await runTransformWith({ catalog: true });
    const code = run.result?.code ?? "";
    const calls = code.match(/registerLocalSvgs\(/g)?.length ?? 0;
    expect(calls).toBe(2);
    const last = code.lastIndexOf("registerLocalSvgs");
    expect(code.slice(last)).toContain('registerLocalSvgs({"testy:house":');
    expect(code.slice(last)).toContain("{ override: false }");
    expect(run.info.join("\n")).toContain(
      "auto-registered 1 catalog icon from 1 source file (testy: 1)",
    );
    expect(run.warnings).toEqual([]);
  });

  it("scans and registers by default, and stays off under catalog: false", async () => {
    await setupCatalog();
    const on = await runTransformWith({});
    expect(on.result?.code?.match(/registerLocalSvgs\(/g)?.length).toBe(2);
    expect(on.result?.code).toContain('"testy:house"');
    expect(on.warnings).toEqual([]);
    const off = await runTransformWith({ catalog: false });
    expect(off.result?.code?.match(/registerLocalSvgs\(/g)?.length).toBe(1);
    expect(off.result?.code).not.toContain("testy:house");
    expect(off.warnings).toEqual([]);
    expect(off.info).toEqual([]);
  });

  it("inherits the svgo and precompiled passes for scanned catalog icons", async () => {
    await setupCatalog();
    const run = await runTransformWith({ catalog: {}, svgo: true, precompiled: true });
    const code = run.result?.code ?? "";
    const catalogCall = code.slice(code.lastIndexOf("registerLocalSvgs"));
    expect(catalogCall).toContain('"precompiled":{"testy:house"');
    expect(catalogCall).not.toContain("catalog register preview");
    expect(catalogCall).not.toContain("2.000");
    expect(catalogCall).toContain('"tag":"svg"');
  });

  it("emits no second call when the scan finds nothing", async () => {
    const run = await runTransformWith({});
    expect(run.result?.code?.match(/registerLocalSvgs\(/g)?.length).toBe(1);
    expect(run.warnings).toEqual([]);
    expect(run.info).toEqual([]);
  });

  it("applies searchPaths to scanned resolution", async () => {
    await setupCatalog();
    const run = await runTransformWith({ catalog: { searchPaths: [root] } });
    expect(run.result?.code).toContain('"testy:house"');
  });

  it("warns on typos in installed collections and leaves rendering to the fallback", async () => {
    await setupCatalog(['<SVG name="testy:hous" />']);
    const run = await runTransformWith({ catalog: true });
    expect(run.warnings.join("\n")).toContain(
      "catalog names did not resolve, but the collection is installed: testy:hous (src/ui/nav.tsx)",
    );
    expect(run.result?.code).toContain('"testy:house"');
    expect(run.result?.code).not.toContain('"testy:hous"');
  });

  it("fails strict builds on unresolvable names from installed collections", async () => {
    await setupCatalog(['<SVG name="testy:hous" />']);
    const run = () => runTransformWith({ catalog: { strict: true } });
    await expect(run()).rejects.toThrow(
      /No source found for these catalog icons: testy:hous \(catalog scan strict mode\)/,
    );
  });

  it("points at install instructions when the collection itself is missing", async () => {
    await writeFixture("src/ui/page.tsx", '<SVG name="ghostly:star" />\n');
    const run = await runTransformWith({ catalog: true });
    expect(run.warnings.join("\n")).toContain(
      'catalog collection "ghostly" is referenced (e.g. ghostly:star in src/ui/page.tsx) but no icon source package is installed. Add @iconify-json/ghostly and rerun.',
    );
  });

  it("warns on dynamic catalog names when the collection is in use", async () => {
    await setupCatalog();
    await writeFixture("src/icons.ts", "const id = 1;\nexport const icon = `testy:${id}`;\n");
    const run = await runTransformWith({ catalog: true });
    expect(run.warnings.join("\n")).toContain("dynamic catalog name at src/icons.ts:2");
    expect(run.warnings.join("\n")).toContain("`testy:${id}`");
  });

  it("warns for dynamic-only usage in an installed collection", async () => {
    await setupCatalog();
    await writeFixture("src/ui/nav.tsx", "<SVG name={`testy:${id}`} />");
    const run = await runTransformWith();
    expect(run.warnings.join("\n")).toContain("dynamic catalog name at src/ui/nav.tsx:1");
    expect(run.result?.code).not.toContain('"testy:house"');
  });

  it("does not recommend icon packages for unrelated string literals", async () => {
    await writeFixture(
      "src/ui/nav.tsx",
      'import "node:fs"; const topic = "app:ready"; export const page = <div className="lg:hidden" />;',
    );
    const run = await runTransformWith();
    expect(run.warnings).toEqual([]);
    expect(run.info).toEqual([]);
  });

  it("reports new dev diagnostics even when the registered set is unchanged", async () => {
    vi.useFakeTimers();
    try {
      await setupCatalog();
      const plugin = svgPlugin({ dirs: [] });
      plugin.configResolved?.({ root } as never);
      const watcher = Object.assign(new EventEmitter(), { add: vi.fn() });
      const logger = { warn: vi.fn() };
      const send = vi.fn();
      plugin.configureServer?.({
        watcher,
        config: { logger },
        ws: { send },
        moduleGraph: { invalidateAll: vi.fn() },
        httpServer: new EventEmitter(),
      } as never);
      await plugin.transform?.call(
        { addWatchFile() {}, warn() {} } as never,
        baseModuleCode,
        localModuleId,
      );
      await writeFixture("src/ui/nav.tsx", '<SVG name="testy:house" /><SVG name="ghostly:star" />');
      watcher.emit("change", join(root, "src/ui/nav.tsx"));
      await vi.advanceTimersByTimeAsync(50);
      await vi.waitFor(() =>
        expect(logger.warn).toHaveBeenCalledWith(
          expect.stringContaining('catalog collection "ghostly"'),
        ),
      );
      expect(send).not.toHaveBeenCalled();
    } finally {
      vi.useRealTimers();
    }
  });
});

describe("catalog name types", () => {
  it("writes generated types by default for installed collections", async () => {
    await setupCatalog();
    await writeFixture("src/ui/extra.tsx", '<SVG name="ghostly:star" />\n');
    const run = await runTransformWith({ catalog: {} });
    const file = await readFile(join(root, "svg-catalog.d.ts"), "utf8");
    expect(file).toContain('import "@mhaadi/svg/catalog-types";');
    expect(file).toContain('declare module "@mhaadi/svg/catalog-types" {');
    expect(file).toContain('"testy": "house"');
    expect(file).not.toContain('"ghostly"');
    expect(run.info.join("\n")).toContain(
      "catalog name types written to svg-catalog.d.ts (testy: 1)",
    );
  });

  it("does not write types under types: false", async () => {
    await setupCatalog();
    const run = await runTransformWith({ catalog: { types: false } });
    expect(existsSync(join(root, "svg-catalog.d.ts"))).toBe(false);
    expect(run.info.join("\n")).not.toContain("catalog name types");
  });

  it("honors a custom types path and skips identical rewrites", async () => {
    await setupCatalog();
    const first = await runTransformWith({ catalog: { types: "types/names.d.ts" } });
    const file = await readFile(join(root, "types", "names.d.ts"), "utf8");
    expect(file).toContain('"testy": "house"');
    expect(first.info.join("\n")).toContain("catalog name types written to types/names.d.ts");
    const second = await runTransformWith({ catalog: { types: "types/names.d.ts" } });
    expect(second.info.join("\n")).not.toContain("catalog name types written");
  });

  it("validates the types option", () => {
    expect(() => localSvgs({ catalog: { types: 5 as never } })).toThrow(
      "The catalog option types must be true or a relative .d.ts path.",
    );
    expect(() => localSvgs({ catalog: { types: "/tmp/x.d.ts" } })).toThrow(
      "Catalog types path must be a relative path ending in .d.ts without globs or '..'.",
    );
    expect(() => localSvgs({ catalog: { types: "icons.ts" } })).toThrow(
      "Catalog types path must be a relative path ending in .d.ts without globs or '..'.",
    );
    expect(() => svgPlugin({ catalog: { collections: ["../lucide"] } })).toThrow(
      "Catalog collections must be an array",
    );
    expect(() => svgPlugin({ catalog: { collections: "lucide" as never } })).toThrow(
      "Catalog collections must be an array",
    );
  });

  it("generates first-use completion at startup without a registry import or source reference", async () => {
    await setupCatalog();
    await writeFixture("src/ui/nav.tsx", "export const empty = true;");
    const plugin = svgPlugin();
    plugin.configResolved?.({ root } as never);
    expect(await readFile(join(root, "svg-catalog.d.ts"), "utf8")).toContain('"testy": "house"');
  });

  it("narrows suggestions without restricting registered source literals", async () => {
    await setupCatalog();
    await writeFixture(
      "node_modules/@iconify-json/other/icons.json",
      JSON.stringify({ icons: { bell: { body: "<path/>" } } }),
    );
    const run = await runTransformWith({ catalog: { collections: ["other"] } });
    const content = await readFile(join(root, "svg-catalog.d.ts"), "utf8");
    expect(content).toContain('"other": "bell"');
    expect(content).not.toContain('"testy"');
    expect(run.result?.code).toContain('"testy:house"');
  });

  it("clears old generated suggestions when no collection remains selected", async () => {
    await setupCatalog();
    await runTransformWith();
    await runTransformWith({ catalog: { collections: [] } });
    expect(await readFile(join(root, "svg-catalog.d.ts"), "utf8")).toContain(
      "interface SvgCatalogIcons {}",
    );
  });

  it("refreshes package updates and clears suggestions after the last package is removed", async () => {
    vi.useFakeTimers();
    try {
      await setupCatalog();
      await writeFixture("package.json", "{}");
      const plugin = svgPlugin({ dirs: [] });
      plugin.configResolved?.({ root } as never);
      const watcher = Object.assign(new EventEmitter(), { add: vi.fn() });
      plugin.configureServer?.({
        watcher,
        config: { logger: { warn: vi.fn() } },
        ws: { send: vi.fn() },
        moduleGraph: { invalidateAll: vi.fn() },
        httpServer: new EventEmitter(),
      } as never);
      const iconsFile = join(root, "node_modules/@iconify-json/testy/icons.json");
      const collection = JSON.parse(await readFile(iconsFile, "utf8"));
      collection.icons.zap = { body: "<path/>" };
      await writeFile(iconsFile, JSON.stringify(collection));
      watcher.emit("change", join(root, "package.json"));
      await vi.advanceTimersByTimeAsync(50);
      await vi.waitFor(async () =>
        expect(await readFile(join(root, "svg-catalog.d.ts"), "utf8")).toContain('"house" | "zap"'),
      );
      await rm(join(root, "node_modules/@iconify-json/testy"), { recursive: true });
      watcher.emit("change", join(root, "package.json"));
      await vi.advanceTimersByTimeAsync(50);
      await vi.waitFor(async () =>
        expect(await readFile(join(root, "svg-catalog.d.ts"), "utf8")).toContain(
          "interface SvgCatalogIcons {}",
        ),
      );
    } finally {
      vi.useRealTimers();
    }
  });
});
