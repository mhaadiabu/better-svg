import { mkdtemp, writeFile, mkdir } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { describe, it, expect, beforeEach } from "vitest";
import { localSvgs, type LocalSvgOptions } from "./plugin";

const naiveSvg = `<!-- generated by icon-designer -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24"><title>Naive</title><path id="keep-me" d="M 1.000 20.000 L 23.000 4.000 Z" /></svg>
`;

let root: string;
const localModuleId = resolve(__dirname, "../core/local.ts");

beforeEach(async () => {
  root = await mkdtemp(join(tmpdir(), "svg-pass-"));
  await mkdir(join(root, "icons"), { recursive: true });
  await writeFile(join(root, "icons", "naive.svg"), naiveSvg);
});

const runTransformWith = (options: LocalSvgOptions) => {
  const plugin = localSvgs({ dirs: ["icons"], ...options });
  plugin.configResolved?.({ root } as never);
  return plugin.transform?.call(
    { addWatchFile() {} } as never,
    `import { registerLocalSvgs } from "@mhaadi/svg/local";\n`,
    localModuleId,
  );
};

const runTransform = (svgo: unknown) =>
  runTransformWith(svgo === undefined ? {} : { svgo: svgo as never });

describe("local discovery svgo option", () => {
  it("registers raw markup when the svgo option is off", async () => {
    const result = await runTransform(undefined);
    expect(result?.code).toContain("<!-- generated by icon-designer -->");
  });

  it("registers markup optimized by the safe preset when the svgo option is true", async () => {
    const result = await runTransform(true);
    expect(result?.code).not.toContain("<!-- generated by icon-designer -->");
    expect(result?.code).not.toContain("1.000");
    expect(result?.code).toContain(String.raw`id=\"keep-me\"`);
  });

  it("registers markup optimized by a full plugin list when one is given", async () => {
    const result = await runTransform({ plugins: ["cleanupIds"] });
    expect(result?.code).toContain("generated by icon-designer");
    expect(result?.code).not.toContain(String.raw`id=\"keep-me\"`);
  });
});

describe("local discovery precompiled option", () => {
  it("emits a precompiled register call when the option is on", async () => {
    const result = await runTransformWith({ precompiled: true });
    expect(result?.code).toContain('"precompiled":{"naive"');
    expect(result?.code).toContain('"tag":"svg"');
    expect(result?.code).toContain('"value":"M 1.000 20.000 L 23.000 4.000 Z"');
    expect(result?.code).toContain(String.raw`id=\"keep-me\"`);
  });

  it("emits plain markup registration when the option is off", async () => {
    const result = await runTransformWith({});
    expect(result?.code).not.toContain("precompiled");
  });

  it("precompiles markup already optimized by the svgo pass", async () => {
    const result = await runTransformWith({ svgo: true, precompiled: true });
    expect(result?.code).not.toContain("1.000");
    expect(result?.code).toContain('"tag":"svg"');
    expect(result?.code).toContain('"value":"keep-me"');
  });

  it("fails the build when a discovered file is not a valid svg", async () => {
    await writeFile(join(root, "icons", "broken.svg"), "definitely not svg", "utf8");
    await expect(runTransformWith({ precompiled: true })).rejects.toThrow(
      /Precompile pass failed for "broken"/,
    );
  });
});
