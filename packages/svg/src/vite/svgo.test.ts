import { describe, it, expect } from "vitest";
import { runSvgoPass, type SvgoOptions } from "./svgo";

const naiveSvg = `<!-- generated by icon-designer -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24">
<title>Naive icon</title>
<desc>Detailed description of the naive icon</desc>
<metadata>Icon by Example Corp</metadata>
<defs>
  <linearGradient id="grad">
    <stop offset="0" stop-color="#000000" />
    <stop offset="1" stop-color="#ffffff" />
  </linearGradient>
</defs>
<path fill="url(#grad)" d="M 1.000 20.000 L 23.000 20.000 L 23.000 4.000 Z" />
<path id="not-referenced-by-anything" d="M 0 0 L 4 4" />
</svg>
`;

const missingSvgoLoader = async () => {
  throw Object.assign(new Error(`Cannot find module 'svgo'`), { code: "ERR_MODULE_NOT_FOUND" });
};

describe("svgo pass", () => {
  it("safe preset shrinks a naive svg while keeping ids, desc, and references", async () => {
    const output = await runSvgoPass(naiveSvg, "brand/naive", { preset: "safe" });
    expect(output.length).toBeLessThan(naiveSvg.length);
    expect(output).not.toContain("<!--");
    expect(output).not.toContain("Example Corp");
    expect(output).not.toContain("1.000");
    expect(output).toContain('viewBox="0 0 24 24"');
    expect(output).toContain('id="grad"');
    expect(output).toContain("url(#grad)");
    expect(output).toContain("<desc>");
    expect(output).toContain('id="not-referenced-by-anything"');
  });

  it("passes a full SVGO plugin list through, so cleanupIds can remove and rename ids", async () => {
    const output = await runSvgoPass(naiveSvg, "brand/naive", {
      plugins: ["removeComments", { name: "cleanupIds" }],
    });
    expect(output).not.toContain("<!--");
    expect(output).not.toContain('id="grad"');
    expect(output).toContain('id="a"');
    expect(output).toContain("url(#a)");
    expect(output).toContain("<desc>");
    expect(output).not.toContain('id="not-referenced-by-anything"');
    expect(output).toContain("<metadata>");
  });

  it("resolves per-file settings from the function form of the option", async () => {
    const options = (name: string) =>
      name === "brand/naive" ? ({ plugins: ["removeComments"] } as const) : false;
    const output = await runSvgoPass(naiveSvg, "brand/naive", options);
    expect(output).not.toContain("<!--");
    expect(output).toContain('<path id="not-referenced-by-anything"');
    await expect(
      runSvgoPass(naiveSvg, "brand/other", options, () => {
        throw new Error("svgo must not load for non-matching files");
      }),
    ).resolves.toBe(naiveSvg);
  });

  it("skips files rejected by the filter without loading svgo", async () => {
    const options: SvgoOptions = { filter: (name) => name.startsWith("social/") };
    expect(
      await runSvgoPass(naiveSvg, "brand/naive", options, () => {
        throw new Error("svgo must not load for filtered files");
      }),
    ).toBe(naiveSvg);
  });

  it("throws a clean install hint when svgo is missing and the pass is on", async () => {
    await expect(
      runSvgoPass(naiveSvg, "brand/naive", { preset: "safe" }, missingSvgoLoader),
    ).rejects.toThrow(/svgo" is not installed/);
  });

  it("rejects custom plugin entries without a function", async () => {
    await expect(
      runSvgoPass(naiveSvg, "brand/naive", {
        plugins: ["removeComments", { name: "custom-hack", fn: "not-a-function" as never }],
      }),
    ).rejects.toThrow(/Custom SVGO plugin "custom-hack" must provide a fn./);
  });

  it("rejects object plugins whose name is not a builtin", async () => {
    await expect(
      runSvgoPass(naiveSvg, "brand/naive", {
        plugins: ["removeComments", { name: "remove-beard" as string }],
      }),
    ).rejects.toThrow(/Unknown SVGO plugin "remove-beard".*Known built-in plugins: .*cleanupIds/s);
  });
});
