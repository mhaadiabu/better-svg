import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";

export type CatalogNameEntry = readonly [collection: string, names: readonly string[]];

const canonicalize = (entries: readonly CatalogNameEntry[]) =>
  entries
    .map(
      ([collection, names]) =>
        [collection, [...new Set(names)].sort()] as const,
    )
    .filter(([, names]) => names.length > 0)
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));

const digestOf = (entries: ReturnType<typeof canonicalize>) => {
  const hash = createHash("sha256");
  for (const [collection, names] of entries) {
    hash.update(`${collection}\u0000${names.join("\u0001")}\u0002`);
  }
  return hash.digest("hex").slice(0, 16);
};

const literal = (value: string) => `"${value}"`;

// d.ts module augmenting @mhaadi/svg/catalog-types with one string-literal
// union per collection. Sorting is codepoint-based for determinism.
export const generateCatalogNameTypes = (entries: readonly CatalogNameEntry[]): string => {
  const sorted = canonicalize(entries);
  const digest = digestOf(sorted);
  const header = [
    "// Generated by @mhaadi/svg. Do not edit.",
    `// digest: ${digest}`,
    `import "@mhaadi/svg/catalog-types";`,
    "",
    `declare module "@mhaadi/svg/catalog-types" {`,
  ];
  if (sorted.length === 0) {
    return [...header, `  interface SvgCatalogIcons {}`, `}`, ""].join("\n");
  }
  const members = sorted.map(
    ([collection, names]) => `    ${literal(collection)}: ${names.map(literal).join(" | ")};`,
  );
  return [...header, `  interface SvgCatalogIcons {`, ...members, `  }`, `}`, ""].join("\n");
};

// Writes the generated d.ts unless the file already holds this exact
// content. Rewrites happen when icon packages change the name lists or
// the scan sees a new collection; the digest comment tracks the change.
export const writeCatalogNameTypes = (
  file: string,
  entries: readonly CatalogNameEntry[],
): "written" | "unchanged" => {
  const content = generateCatalogNameTypes(entries);
  let existing: string | undefined;
  try {
    existing = readFileSync(file, "utf8");
  } catch {
    existing = undefined;
  }
  if (existing === content) return "unchanged";
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, content);
  return "written";
};
